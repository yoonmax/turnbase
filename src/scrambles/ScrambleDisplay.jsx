import { useEffect, useMemo, useRef, useState } from 'react';
import gsap from 'gsap';
import { ChevronLeft, Copy, PenLine, RefreshCw } from 'lucide-react';
import { useApp } from '../app/store.js';
import { copyText } from '../utils/download.js';
import { prefersReducedMotion } from '../app/appearance.js';
import { Modal } from '../components/Modal.jsx';
import { parseAlgorithm } from '../cube/CubeNotationParser.js';
import { getPuzzle } from './PuzzleRegistry.js';

function OwnScrambleDialog({ open, onClose }) {
  const session = useApp((s) => s.currentSession());
  const setOwnScramble = useApp((s) => s.setOwnScramble);
  const [text, setText] = useState('');
  const puzzle = getPuzzle(session?.puzzle);
  const parsed = useMemo(() => (puzzle.cube ? parseAlgorithm(text, { n: puzzle.cube }) : { ok: true, moves: [] }), [text, puzzle]);
  const empty = !text.trim();
  const valid = !empty && parsed.ok && (!puzzle.cube || parsed.moves.length > 0);
  return (
    <Modal open={open} onClose={onClose} title="Use your own scramble" testId="own-scramble">
      <p className="m-0 mb-3 text-[0.8125rem] text-graphite">
        Paste a scramble from anywhere, for example one generated by TNoodle, the official WCA program. The next solve records it as entered by you.
      </p>
      <textarea className="field notation w-full" rows={3} spellCheck={false} aria-label="Scramble" value={text} data-testid="own-scramble-input" onChange={(e) => setText(e.target.value)} />
      {!empty && !parsed.ok ? <p className="m-0 mt-1 text-[0.8125rem] text-danger">{parsed.error.message}</p> : null}
      {!puzzle.cube ? <p className="m-0 mt-1 text-[0.8125rem] text-graphite">turnbase cannot check {puzzle.name} notation, so it is stored as you type it.</p> : null}
      <div className="mt-4 flex justify-end gap-2">
        <button type="button" className="btn" onClick={onClose}>
          Cancel
        </button>
        <button
          type="button"
          className="btn btn-primary"
          disabled={!valid}
          data-testid="own-scramble-use"
          onClick={() => {
            setOwnScramble(text.trim());
            setText('');
            onClose();
          }}
        >
          Use this scramble
        </button>
      </div>
    </Modal>
  );
}

export function scrambleSizeClass(text = '') {
  if (text.length > 260) return 0.72;
  if (text.length > 130) return 0.82;
  return 1;
}

export function ScrambleDisplay() {
  const scramble = useApp((s) => s.scramble);
  const pending = useApp((s) => s.scramblePending);
  const error = useApp((s) => s.scrambleError);
  const newScramble = useApp((s) => s.newScramble);
  const previousScramble = useApp((s) => s.previousScramble);
  const historyCount = useApp((s) => s.scrambleHistory.length);
  const pushToast = useApp((s) => s.pushToast);
  const textRef = useRef(null);
  const [entering, setEntering] = useState(false);

  // Replacing a scramble is a small event: the old one is gone, this one is new.
  useEffect(() => {
    if (!textRef.current || prefersReducedMotion()) return;
    gsap.fromTo(textRef.current, { opacity: 0, y: 3 }, { opacity: 1, y: 0, duration: 0.22, ease: 'power2.out' });
  }, [scramble?.id]);

  const fit = scrambleSizeClass(scramble?.text);

  return (
    <div className="focus-fade reveal-host flex flex-col items-center gap-1 px-4 sm:px-10 w-full" style={{ paddingTop: 'calc(var(--page-top) + 12px)' }}>
      <div
        ref={textRef}
        className="notation text-center leading-[1.55] max-w-[62ch] min-h-[3.1em] whitespace-pre-line"
        data-testid="scramble-text"
        style={{ fontSize: `calc(clamp(0.8125rem, 1.45cqw, 1.125rem) * var(--scramble-scale, 1) * ${fit})` }}
      >
        {error ? (
          <span className="text-danger">The scramble generator did not respond.</span>
        ) : scramble ? (
          scramble.text
        ) : (
          <span className="text-faint">Generating a scramble</span>
        )}
      </div>
      <div className="reveal-on-hover flex items-center gap-0.5">
        <button
          type="button"
          className="icon-btn"
          aria-label="Previous scramble"
          title="Previous scramble"
          disabled={!historyCount}
          data-testid="scramble-previous"
          onClick={previousScramble}
        >
          <ChevronLeft size={15} strokeWidth={1.6} />
        </button>
        <button
          type="button"
          className="icon-btn"
          aria-label={error ? 'Retry' : 'New scramble'}
          title="New scramble"
          data-testid="scramble-new"
          disabled={pending}
          onClick={newScramble}
        >
          <RefreshCw size={14} strokeWidth={1.6} />
        </button>
        <button
          type="button"
          className="icon-btn"
          aria-label="Copy scramble"
          title="Copy scramble"
          disabled={!scramble}
          data-testid="scramble-copy"
          onClick={async () => {
            await copyText(scramble.text);
            pushToast({ message: 'Scramble copied', durationMs: 1800 });
          }}
        >
          <Copy size={14} strokeWidth={1.6} />
        </button>
        <button type="button" className="icon-btn" aria-label="Use your own scramble" title="Use your own scramble" data-testid="scramble-own" onClick={() => setEntering(true)}>
          <PenLine size={14} strokeWidth={1.6} />
        </button>
      </div>
      <OwnScrambleDialog open={entering} onClose={() => setEntering(false)} />
    </div>
  );
}
